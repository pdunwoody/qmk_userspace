void oled_render_logo(void) {
    oled_write_raw_P(de_logo, sizeof(de_logo));
}

// Line 0 (21 chars): "LAYER " + layer name inverted (15 chars)
void oled_render_layer_state(void) {
    oled_write_P(PSTR("LAYER "), false);
    switch (get_highest_layer(layer_state)) {
        case _BASE:       oled_write_P(PSTR("BASE           "), true);  break;
        case _NUMBERS:    oled_write_P(PSTR("NUMBERS        "), true);  break;
        case _EXTRA:      oled_write_P(PSTR("EXTRA          "), true);  break;
        case _FUNCTION:   oled_write_P(PSTR("FUNCTION       "), true);  break;
        case _SYMBOLS:    oled_write_P(PSTR("SYMBOLS        "), true);  break;
        case _NAVIGATION: oled_write_P(PSTR("NAVIGATE       "), true);  break;
        case _MEDIA:      oled_write_P(PSTR("MEDIA          "), true);  break;
        case _QWERTY:     oled_write_P(PSTR("QWERTY         "), true);  break;
        default:          oled_write_P(PSTR("UNKNOWN        "), true);  break;
    }
}

// Line 1 (21 chars): modifier keys, inverted when active
void oled_render_mod_state(void) {
    uint8_t mods = get_mods() | get_oneshot_mods();
    oled_write_P(PSTR(" "), false);
    oled_write_P(PSTR("SFT"), (mods & MOD_MASK_SHIFT) != 0);
    oled_write_P(PSTR("  "), false);
    oled_write_P(PSTR("CTL"), (mods & MOD_MASK_CTRL) != 0);
    oled_write_P(PSTR("  "), false);
    oled_write_P(PSTR("ALT"), (mods & MOD_MASK_ALT) != 0);
    oled_write_P(PSTR("  "), false);
    oled_write_P(PSTR("GUI"), (mods & MOD_MASK_GUI) != 0);
    oled_write_P(PSTR("  "), false);
}

// Line 2 (21 chars): Caps Lock and Caps Word indicators
void oled_render_caps_state(void) {
    led_t led_state = host_keyboard_led_state();
    oled_write_P(PSTR(" "), false);
    oled_write_P(PSTR("CAPS"), led_state.caps_lock);
    oled_write_P(PSTR(" "), false);
    oled_write_P(PSTR("WORD"), is_caps_word_on());
    oled_write_P(PSTR("           "), false);
}

// Line 3 (21 chars): WPM count + proportional progress bar
void oled_render_wpm(void) {
    uint8_t wpm = (uint8_t)get_current_wpm();
    char buf[8];
    snprintf(buf, sizeof(buf), "WPM:%03u", wpm);
    oled_write(buf, false);
    uint8_t filled = (wpm >= 100) ? 14 : (wpm * 14 / 100);
    for (uint8_t i = 0; i < 14; i++) {
        oled_write_P(PSTR(" "), i < filled);
    }
}

bool oled_task_user(void) {
    if (is_keyboard_master()) {
        oled_render_layer_state();
        oled_render_mod_state();
        oled_render_caps_state();
        oled_render_wpm();
    } else {
        oled_render_logo();
    }
    return false;
}
